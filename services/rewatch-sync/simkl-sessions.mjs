import { createHash, randomBytes, randomUUID } from 'node:crypto';
import { lstat, mkdir, open, readFile, rename } from 'node:fs/promises';
import { dirname } from 'node:path';

const hash = value => createHash('sha256').update(value).digest('hex');
const VALID_TOKEN = /^[a-f0-9]{64}$/;
const VALID_UUID_V4 = /^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/i;
const VALID_PRINCIPAL = /^simkl:[1-9][0-9]{0,15}$/;
const clone = value => structuredClone(value);

/**
 * Scoped, revocable, expiring replay tokens. Device identity is long-lived and
 * bound to a verified Simkl principal plus one randomly generated installation UUID.
 *
 * Installation UUID is generated by the client ONCE PER LOCAL PROFILE, retained
 * across upgrades, and never treated as proof of a Simkl account. The VPS first
 * verifies the existing Simkl login and issues the credential afterward.
 *
 * The database stores SHA256 hashes of both credential and installation binding;
 * no Simkl bearer token or new replay bearer token is persisted in plaintext.
 *
 * One writer/process owns this file. This is not a multi-process database.
 */
export class SimklReplayCredentials {
  constructor(file, { now = () => Date.now(), lifetimeMs = 24 * 60 * 60 * 1000 } = {}) {
    if (!Number.isSafeInteger(lifetimeMs) || lifetimeMs < 60_000 ||
        lifetimeMs > 48 * 60 * 60 * 1000) {
      throw Error('Invalid replay credential lifetime');
    }
    this.file = file;
    this.now = now;
    this.lifetimeMs = lifetimeMs;
    this.data = { schemaVersion: 2, devices: {}, bindings: {} };
    this.chain = Promise.resolve();
  }

  async init() {
    try {
      const status = await lstat(this.file);
      if (!status.isFile() || (status.mode & 0o077) !== 0) {
        throw Error('Replay credential store must be a private regular file');
      }
      const obj = JSON.parse(await readFile(this.file, 'utf8'));
      if (obj.schemaVersion !== 2 || !obj.devices ||
          typeof obj.devices !== 'object' || Array.isArray(obj.devices) ||
          !obj.bindings || typeof obj.bindings !== 'object' ||
          Array.isArray(obj.bindings) ||
          Object.entries(obj.devices).some(([key, item]) =>
            !VALID_TOKEN.test(key) || !item ||
            !VALID_PRINCIPAL.test(item.principal) ||
            typeof item.deviceId !== 'string' ||
            !item.deviceId.startsWith('simkl-device:') ||
            typeof item.revoked !== 'boolean' ||
            !Number.isSafeInteger(item.expiresAtEpochMs)) ||
          Object.entries(obj.bindings).some(([key, item]) =>
            !VALID_TOKEN.test(key) || !item ||
            !VALID_PRINCIPAL.test(item.principal) ||
            typeof item.deviceId !== 'string' ||
            !item.deviceId.startsWith('simkl-device:'))) {
        throw Error('Unsupported or corrupted replay credential store');
      }
      this.data = obj;
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      await mkdir(dirname(this.file), { recursive: true, mode: 0o700 });
    }
  }

  serialize(fn) {
    const result = this.chain.then(fn);
    this.chain = result.catch(() => {});
    return result;
  }

  async persist(next) {
    const temp = this.file + '.' + randomUUID() + '.tmp';
    const handle = await open(temp, 'wx', 0o600);
    try {
      await handle.writeFile(JSON.stringify(next) + '\n');
      await handle.sync();
    } finally { await handle.close(); }
    await rename(temp, this.file);
    const directory = await open(dirname(this.file), 'r');
    try { await directory.sync(); } finally { await directory.close(); }
  }

  identify(token) {
    if (typeof token !== 'string' || !VALID_TOKEN.test(token)) return null;
    const record = this.data.devices[hash(token)];
    if (!record || record.revoked || record.expiresAtEpochMs <= this.now()) return null;
    return { principal: record.principal, deviceId: record.deviceId };
  }

  async issue(principal, clientInstallationId) {
    if (typeof principal !== 'string' || !VALID_PRINCIPAL.test(principal)) {
      throw Error('Only Simkl-verified principals may obtain credentials');
    }
    if (typeof clientInstallationId !== 'string' ||
        !VALID_UUID_V4.test(clientInstallationId)) {
      throw Error('A stable, random v4 client installation ID is required');
    }
    const normalized = clientInstallationId.toLowerCase();
    return this.serialize(async () => {
      const now = this.now();
      const token = randomBytes(32).toString('hex');
      const bindingKey = hash(principal + '\x00' + normalized);
      const existing = this.data.bindings[bindingKey];
      const deviceId = existing?.deviceId ?? ('simkl-device:' + randomUUID());
      const expiresAtEpochMs = now + this.lifetimeMs;
      const next = clone(this.data);
      next.bindings[bindingKey] = { principal, deviceId };
      for (const [key, item] of Object.entries(next.devices)) {
        // Rotation revokes the previous replay token, without changing the
        // device ID referenced by existing offline events.
        if (item.revoked || item.expiresAtEpochMs <= now ||
            (item.principal === principal && item.deviceId === deviceId)) {
          delete next.devices[key];
        }
      }
      next.devices[hash(token)] = {
        principal, deviceId, revoked: false, expiresAtEpochMs
      };
      await this.persist(next);
      this.data = next;
      return { token, deviceId, expiresAtEpochMs };
    });
  }

  async revoke(token) {
    return this.serialize(async () => {
      if (typeof token !== 'string' || !VALID_TOKEN.test(token) ||
          !this.data.devices[hash(token)]) return false;
      const next = clone(this.data);
      next.devices[hash(token)].revoked = true;
      await this.persist(next);
      this.data = next;
      return true;
    });
  }
}
